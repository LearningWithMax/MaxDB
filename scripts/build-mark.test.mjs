import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { BUILD_WORDS, wordFor, buildCss, nextBuild } from './lib/build.mjs';

// The owner's version word (2026-10-28): a word in the footer next to "Built with Claude", a new one on every push to main.
// Only he knows what each word means; Claude tells him the word after each push and he checks it on his phone. The word comes
// from css/build.css, a file the browser really loads, so a stale cache shows a stale word instead of lying.
const read = (p) => fs.readFileSync(new URL('../' + p, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const info = JSON.parse(read('scripts/lib/build-info.json'));

test('the word list: at least 30 single words, each unique, short enough for the footer, no dashes or digits', () => {
  assert.ok(BUILD_WORDS.length >= 30);
  assert.equal(new Set(BUILD_WORDS).size, BUILD_WORDS.length, 'no word twice');
  for (const w of BUILD_WORDS) assert.match(w, /^[A-Z][a-z]{2,11}$/, w);
});

test('wordFor: update 1 is the first word, each update takes the next, the list wraps around, update 0 is no word', () => {
  assert.equal(wordFor(1), BUILD_WORDS[0]);
  assert.equal(wordFor(2), BUILD_WORDS[1]);
  assert.equal(wordFor(BUILD_WORDS.length), BUILD_WORDS[BUILD_WORDS.length - 1]);
  assert.equal(wordFor(BUILD_WORDS.length + 1), BUILD_WORDS[0]);
  assert.equal(wordFor(0), '');
  assert.throws(() => wordFor(-1));
  assert.throws(() => wordFor(1.5));
});

test('buildCss: one custom property holding a middle dot and the word, and an empty one before the first stamp', () => {
  const css = buildCss(2);
  assert.match(css, /^\/\* Generated by scripts\/stamp\.mjs\. Do not edit\./);
  assert.ok(css.includes(`:root{--build-mark:" \\00b7 ${wordFor(2)}";}`), css);
  assert.ok(buildCss(0).includes(':root{--build-mark:"";}'));
  assert.doesNotMatch(css, /[\u2013\u2014]/, 'no dashes');
  assert.ok(css.endsWith('\n'));
});

test('nextBuild: the next number and the time in UTC to the minute', () => {
  assert.deepEqual(nextBuild({ n: 4, at: 'x' }, new Date(Date.UTC(2026, 9, 28, 14, 5, 59))), { n: 5, at: '2026-10-28 14:05 UTC' });
  assert.deepEqual(nextBuild({ n: 0, at: '' }, new Date(Date.UTC(2026, 0, 2, 3, 4))), { n: 1, at: '2026-01-02 03:04 UTC' });
});

test('build-info.json and css/build.css agree: the stylesheet is the one stamp.mjs would write for this number', () => {
  assert.ok(Number.isInteger(info.n) && info.n >= 0);
  assert.match(info.at, /^(\d{4}-\d\d-\d\d \d\d:\d\d UTC)?$/);
  assert.equal(read('css/build.css'), buildCss(info.n), 'run: node scripts/stamp.mjs');
});

test('the page loads css/build.css and the footer has an empty mark inside the Built with Claude line, drawn from the variable', () => {
  const html = read('index.html');
  const foot = html.slice(html.indexOf('<footer'), html.indexOf('</footer>'));
  assert.match(html, /<link rel="stylesheet" href="css\/build\.css">/);
  assert.match(foot, /<span class="built-with">Built with Claude<span class="build-mark" aria-hidden="true"><\/span><\/span>/);
  assert.equal([...foot.matchAll(/Built with Claude/g)].length, 1);
  const chrome = read('css/chrome.css');
  assert.match(chrome, /footer \.build-mark::before\s*\{[^}]*content:\s*var\(--build-mark,\s*""\)/);
  assert.match(chrome, /footer \.build-mark::before\s*\{[^}]*opacity:\s*\.\d+/, 'dimmer than the line it sits on');
});
