// Copies the pinned third-party files into vendor/ and writes vendor/MANIFEST.json (sha256, bytes, gzip bytes).
//   node scripts/vendor.mjs
// Versions are pinned here. To upgrade: change a version, run this, commit vendor/. check.mjs verifies the
// manifest so a vendored file can never change silently.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const THREE = '0.184.0', GSAP = '3.15.0', ATLAS = '2.0.2';
const jsd = (pkg, file) => `https://cdn.jsdelivr.net/npm/${pkg}/${file}`;
const add = (from, to) => ({ from, to });

const list = [
  add(jsd(`three@${THREE}`, 'build/three.module.min.js'), 'vendor/three/three.module.min.js'),
  add(jsd(`three@${THREE}`, 'build/three.core.min.js'), 'vendor/three/three.core.min.js'),
  add(jsd(`three@${THREE}`, 'LICENSE'), 'vendor/three/LICENSE'),
  ...['environments/RoomEnvironment.js', 'lines/Line2.js', 'lines/LineSegments2.js', 'lines/LineGeometry.js',
      'lines/LineSegmentsGeometry.js', 'lines/LineMaterial.js']
    .map((f) => add(jsd(`three@${THREE}`, `examples/jsm/${f}`), `vendor/three/addons/${f}`)),
  ...['index.js', 'gsap-core.js', 'CSSPlugin.js']
    .map((f) => add(jsd(`gsap@${GSAP}`, f), `vendor/gsap/${f}`)),
  add(jsd(`world-atlas@${ATLAS}`, 'countries-110m.json'), 'vendor/data/countries-110m.json'),
];

async function get(url, opts) {
  const r = await fetch(url, opts);
  if (!r.ok) throw new Error(`${r.status} for ${url}`);
  return Buffer.from(await r.arrayBuffer());
}

const files = {};
const gsapNote = Buffer.from(`GSAP ${GSAP} is vendored unmodified from the npm package gsap.
It is free under the GreenSock Standard 'No Charge' License: https://gsap.com/standard-license
`);
for (const { from, to } of list) {
  const buf = await get(from);
  const dest = path.join(root, to);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, buf);
  files[to] = {
    sha256: crypto.createHash('sha256').update(buf).digest('hex'),
    bytes: buf.length,
    gzipBytes: zlib.gzipSync(buf, { level: 9 }).length,
    source: from,
  };
}
const noteRel = 'vendor/gsap/LICENSE.md';
fs.writeFileSync(path.join(root, noteRel), gsapNote);
files[noteRel] = { sha256: crypto.createHash('sha256').update(gsapNote).digest('hex'), bytes: gsapNote.length, gzipBytes: zlib.gzipSync(gsapNote).length, source: 'generated by scripts/vendor.mjs' };
// the fonts are vendored by scripts/vendor-fonts.mjs: keep their manifest entries when this script rewrites the file
const manifestPath = path.join(root, 'vendor/MANIFEST.json');
const previous = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')).files : {};
for (const [key, meta] of Object.entries(previous)) if (key.startsWith('vendor/fonts/')) files[key] = meta;
fs.writeFileSync(manifestPath, JSON.stringify({ versions: { three: THREE, gsap: GSAP, 'world-atlas': ATLAS }, files }, null, 2) + '\n');

const sum = (re) => Object.entries(files).filter(([k]) => re.test(k)).reduce((a, [, v]) => a + v.gzipBytes, 0);
for (const [k, v] of Object.entries(files)) console.log(String(v.bytes).padStart(8), String(v.gzipBytes).padStart(8), k);
console.log(`\nthree core + module, gzip: ${sum(/three\.(module|core)\.min\.js$/)} bytes`);
console.log(`three addons, gzip: ${sum(/three\/addons\//)} bytes`);
console.log(`gsap, gzip: ${sum(/gsap\/(index|gsap-core|CSSPlugin)\.js$/)} bytes`);
