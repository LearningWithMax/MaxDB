// The version word in the footer, next to "Built with Claude" (the owner's idea, 2026-10-28). Every push to main takes the next
// word from this list, and Claude tells him which one it should be, so he can check on his phone that he has the new version.
// The list starts as the periodic table (the owner's background, and the chrome beads: Chromium is the 24th). He can swap in
// words of his own that mean something to him; this file is public, so only words he is happy to show. One word each, a capital
// letter first, 3 to 12 letters, no dashes or digits (scripts/build-mark.test.mjs checks that).
export const BUILD_WORDS = [
  'Hydrogen', 'Helium', 'Lithium', 'Beryllium', 'Boron', 'Carbon', 'Nitrogen', 'Oxygen', 'Fluorine', 'Neon',
  'Sodium', 'Magnesium', 'Aluminum', 'Silicon', 'Phosphorus', 'Sulfur', 'Chlorine', 'Argon', 'Potassium', 'Calcium',
  'Scandium', 'Titanium', 'Vanadium', 'Chromium', 'Manganese', 'Iron', 'Cobalt', 'Nickel', 'Copper', 'Zinc',
];

// Update 1 takes the first word, update 2 the second, and after the last word the list starts again. Update 0 (before the first stamp) has none.
export function wordFor(n) {
  if (!Number.isInteger(n) || n < 0) throw new Error('build number must be a whole number, 0 or more: ' + n);
  return n === 0 ? '' : BUILD_WORDS[(n - 1) % BUILD_WORDS.length];
}

// css/build.css. The footer reads this variable, so the word on screen is the word in the stylesheet the browser really loaded:
// a phone that kept an old copy shows the old word. \00b7 is the middle dot.
export function buildCss(n) {
  const word = wordFor(n);
  return '/* Generated by scripts/stamp.mjs. Do not edit. The footer word next to "Built with Claude" comes from here, so it shows which stylesheet the browser really has. */\n'
    + ':root{--build-mark:"' + (word ? ' \\00b7 ' + word : '') + '";}\n';
}

// The next stamp: one more than the last, and the time in UTC to the minute.
export function nextBuild(info, date) {
  const p = (v) => String(v).padStart(2, '0');
  const at = date.getUTCFullYear() + '-' + p(date.getUTCMonth() + 1) + '-' + p(date.getUTCDate()) + ' ' + p(date.getUTCHours()) + ':' + p(date.getUTCMinutes()) + ' UTC';
  return { n: info.n + 1, at };
}
